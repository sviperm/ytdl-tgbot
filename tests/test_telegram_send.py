@pytest_asyncio.fixture(scope="session", loop_scope="session")
async def bot():
    """One authorized client for the whole run.

    Deliberately session-scoped *and* backed by a session file on disk: Telegram
    rate-limits bot authorization hard (a per-test login earned a FLOOD_WAIT of
    3169s), so this signs in once and every later run resumes from
    ``data/ytdl_test_bot.session`` without signing in at all.
    """
    if not _TOKEN:
        pytest.skip("set TG_TEST_BOT_TOKEN to a dev bot token (never TG_BOT_API)")
    if not (Config.API_ID and Config.API_HASH):
        pytest.skip("MTProto needs TG_APP_ID and TG_API_HASH, same as the real bot")
    if _TOKEN == Config.BOT_TOKEN:
        pytest.fail("TG_TEST_BOT_TOKEN is the production token; use a separate dev bot")

    os.makedirs(Config.DATA_DIR, exist_ok=True)
    app = Client(
        "ytdl_test_bot", api_id=Config.API_ID, api_hash=Config.API_HASH,
        bot_token=_TOKEN, workdir=Config.DATA_DIR,
    )
    try:
        await app.start()
    except FloodWait as e:
        # Rate limiting is an environment condition, not a code failure: skip with
        # the wait so the tier reports a reason instead of a wall of errors.
        pytest.skip(f"Telegram is rate-limiting this bot's login: retry in {e.value}s")
    try:
        yield app
    finally:
        await app.stop()


