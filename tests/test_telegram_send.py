# --- single video ------------------------------------------------------------

async def test_single_video_uploads_and_returns_reusable_file_id(client, chat_id, landscape):
    thumb = await VideoProcessor().make_thumbnail(landscape)
    post = _post([MediaItem("video", landscape, thumb)],
                 title="[test] single video 1280x720 + thumbnail")
    status = StatusRecorder()

    result = await TelegramSender().send_post(client, chat_id, post, status)

    assert result.file_id, "no file_id came back, so nothing could ever be cached"
    message = client.videos[-1]
    assert message.video is not None, "Telegram filed it as something other than a video"
    # The dimensions the bot declares are what Telegram plays it back at; a wrong
    # pair is the difference between a video and a letterboxed sliver.
    assert (message.video.width, message.video.height) == (1280, 720)
    assert message.video.duration == 3
    assert message.video.thumbs, "no thumbnail survived the upload"
    # The upload progress bar is a product requirement, not decoration.
    assert any("Uploading" in text and "MB" in text for text in status.texts), \
        f"no upload progress was reported, only: {status.texts}"


async def test_vertical_video_arrives_vertical(client, chat_id, portrait):
    post = _post([MediaItem("video", portrait)],
                 title="[test] vertical video 720x1280", width=720, height=1280)

    await TelegramSender().send_post(client, chat_id, post, StatusRecorder())

    video = client.videos[-1].video
    assert video.height > video.width, \
        f"shorts must stay portrait, Telegram reports {video.width}x{video.height}"


async def test_caption_html_parses_and_links_to_the_cleaned_source(client, chat_id, landscape):
    # Characters that would break a naive caption builder, plus a tracking param
    # that must not reach the link Telegram shows.
    title = '[test] caption escaping: & <angle> "quoted"'
    shared = "https://youtu.be/aqz-KE-bpKQ?si=lIrGXWyKMLmMbtGz"
    post = _post([MediaItem("video", landscape)], title=title, url=shared)

    await TelegramSender().send_post(client, chat_id, post, StatusRecorder())

    message = client.videos[-1]
    # Telegram hands the text back decoded, so this proves the escaping round-trips
    # instead of leaking &amp; into what the user reads.
    assert message.caption == title
    links = [e for e in (message.caption_entities or [])
             if e.type == MessageEntityType.TEXT_LINK]
    assert len(links) == 1, f"expected one source link, got {message.caption_entities}"
    assert links[0].url == clean_url(shared)


async def test_stored_file_id_resends_without_the_file(client, chat_id, landscape):
    """The cache path: a second request must resend from the id alone."""
    post = _post([MediaItem("video", landscape)],
                 title="[test] cached resend by file_id")
    result = await TelegramSender().send_post(client, chat_id, post, StatusRecorder())
    assert result.file_id

    os.remove(landscape)  # prove nothing local is read on the cached path
    await TelegramSender().send_cached_video(client, chat_id, result.file_id, post.meta)

    resent = client.videos[-1]
    assert resent.video is not None
    assert (resent.video.width, resent.video.height) == (1280, 720)
    assert resent.caption == post.meta.title


