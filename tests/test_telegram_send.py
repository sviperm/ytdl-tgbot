async def test_mixed_album_captions_only_the_first_item(client, chat_id, tmp_path, landscape):
    """The Instagram carousel shape: one video plus photos, one caption."""
    live_env.skip_unless_ffmpeg()
    images = [_make_image(tmp_path / f"carousel_{i}.jpg") for i in range(2)]
    post = _post(
        [
            MediaItem("video", landscape, await VideoProcessor().make_thumbnail(landscape)),
            MediaItem("image", images[0]),
            MediaItem("image", images[1]),
        ],
        title="[test] album: 1 video + 2 photos, caption on the first only",
    )

    await TelegramSender().send_post(client, chat_id, post, StatusRecorder())

    assert len(client.groups) == 1, "a 3-item post must go as one album"
    album = client.groups[0]
    assert len(album) == 3
    assert album[0].caption == post.meta.title
    # Telegram shows an album's caption from its first item; captions on the rest
    # would render as stray text under the photos.
    assert all(not m.caption for m in album[1:])


async def test_album_beyond_ten_items_is_chunked(client, chat_id, tmp_path):
    live_env.skip_unless_ffmpeg()
    images = [_make_image(tmp_path / f"bulk_{i}.jpg", 320, 240) for i in range(12)]
    post = _post([MediaItem("image", path) for path in images],
                 title="[test] album chunking: 12 photos -> 10 + 2")

    await TelegramSender().send_post(client, chat_id, post, StatusRecorder())

    # Telegram rejects an album larger than 10, so 12 must arrive as 10 + 2.
    assert [len(group) for group in client.groups] == [10, 2]
    assert client.groups[0][0].caption == post.meta.title


# --- the whole pipeline ------------------------------------------------------

@pytest.mark.network
async def test_orchestrator_end_to_end(client, chat_id, bot, tmp_path, monkeypatch):
    """A real link in, a real vertical video out, a real cache row written.

    Every other test here hands the sender a file that was never downloaded. This
    one runs what a user actually triggers: probe, download, transcode, upload,
    cache, cleanup.
    """
    live_env.skip_unless_youtube_env_ready()
    downloads = tmp_path / "downloads"
    downloads.mkdir()
    monkeypatch.setattr(Config, "DOWNLOAD_DIR", str(downloads))

    db = Database(str(tmp_path / "cache.db"))
    await db.initialize()
    ytdlp, video = YtDlpClient(), VideoProcessor()
    registry = PlatformRegistry([
        YouTubePlatform(ytdlp, video),
        GenericPlatform(ytdlp, video),
    ])
    orchestrator = DownloadOrchestrator(registry, TelegramSender(), db, max_concurrent=1)
    incoming = Incoming(bot, chat_id)

    await orchestrator.handle_url(client, incoming, _E2E_URL)

    assert client.videos, "nothing reached Telegram; check the status message in the chat"
    sent = client.videos[-1].video
    assert sent.height > sent.width, f"short arrived as {sent.width}x{sent.height}"
    assert sent.duration > 0
    # handle_url swallows its own errors into a status message, so the cache row is
    # what proves the run actually succeeded rather than reporting a failure.
    file_id = await db.get_file_id("youtube", _E2E_VIDEO_ID)
    assert file_id, "no cache row written, so the send path did not complete"
    assert os.listdir(downloads) == [], "the per-request work dir was not cleaned up"
