# --- media fixtures ----------------------------------------------------------

def _make_video(path, width, height, seconds=3):
    """A tiny H.264/AAC clip of exactly the given size, via ffmpeg."""
    subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", f"testsrc2=size={width}x{height}:rate=25:duration={seconds}",
            "-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}",
            "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "64k", "-movflags", "+faststart",
            "-shortest", str(path),
        ],
        check=True, capture_output=True,
    )
    return str(path)


def _make_image(path, width=800, height=600):
    subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", f"testsrc2=size={width}x{height}:duration=1",
            "-frames:v", "1", str(path),
        ],
        check=True, capture_output=True,
    )
    return str(path)


# --- test doubles ------------------------------------------------------------

class RecordingClient:
    """The real Pyrogram client, keeping every Message the sender produced.

    ``send_post`` only hands back a file_id, but these tests need Telegram's own
    view of what arrived — dimensions, caption entities — so the Messages are
    captured out here instead of by widening the production return type.
    """

    def __init__(self, client):
        self._client = client
        self.videos = []
        self.photos = []
        self.groups = []
        # A fresh upload passes a local path; a cached resend passes a file_id
        # string. Keeping the kwargs is the only way to tell those apart.
        self.video_kwargs = []

    def __getattr__(self, name):
        return getattr(self._client, name)

    async def send_video(self, **kwargs):
        self.video_kwargs.append(kwargs)
        message = await self._client.send_video(**kwargs)
        self.videos.append(message)
        return message

    async def send_photo(self, **kwargs):
        message = await self._client.send_photo(**kwargs)
        self.photos.append(message)
        return message

    async def send_media_group(self, **kwargs):
        messages = await self._client.send_media_group(**kwargs)
        self.groups.append(messages)
        return messages

    @property
    def all_messages(self):
        return [*self.videos, *self.photos, *(m for g in self.groups for m in g)]

    async def cleanup(self):
        by_chat = {}
        for message in self.all_messages:
            by_chat.setdefault(message.chat.id, []).append(message.id)
        for chat_id, ids in by_chat.items():
            try:
                await self._client.delete_messages(chat_id, ids)
            except Exception as e:  # a bot may only delete its own, and only for 48h
                print(f"cleanup skipped for {chat_id}: {e}")


class StatusRecorder:
    """Stands in for StatusReporter, keeping the progress text for assertions."""

    def __init__(self):
        self.texts = []
        self.done_called = False

    async def set(self, text):
        self.texts.append(text)

    async def done(self):
        self.done_called = True


class Incoming:
    """Stands in for the user's message.

    ``reply_text`` returns a *real* Telegram message, so StatusReporter's edits and
    final delete are exercised for real too.
    """

    def __init__(self, bot, chat_id):
        self._bot = bot
        self.chat = SimpleNamespace(id=chat_id)
        self.from_user = SimpleNamespace(id=chat_id)
        self.status = None

    async def reply_text(self, text):
        self.status = await self._bot.send_message(self.chat.id, text)
        return self.status


