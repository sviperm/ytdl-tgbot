"""Real uploads to a dev bot: the one path fakes cannot vouch for.

``tests/test_telegram_sender.py`` proves the sender calls Pyrogram correctly. It
cannot prove Telegram *accepts* the result — that the caption HTML parses, that a
vertical video arrives vertical instead of squashed, that a stored ``file_id``
really resends, that an album chunks. Those only fail against the live API, and
they are exactly the failures users see.

Opt-in twice over (marker + ``RUN_TELEGRAM_TESTS=1``) and it needs a **dev** bot,
never the production one: uploads land in a real chat.

    TG_TEST_BOT_TOKEN=<dev bot token>   # from BotFather, NOT TG_BOT_API
    TG_TEST_CHAT_ID=<your user id>      # press Start on the dev bot first —
                                        # a bot cannot open a conversation
    RUN_TELEGRAM_TESTS=1 ./venv/bin/pytest -q -m telegram

Messages are left in the chat on purpose: seeing them is half the point. Set
``TG_TEST_CLEANUP=1`` to have each test delete what it sent.

Media is generated by ffmpeg at run time rather than committed, so the repo keeps
no binary fixtures and the dimensions under test are stated in the test itself.
"""

